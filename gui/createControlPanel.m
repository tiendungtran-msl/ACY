function [target_tables, buttons, checkboxes] = createControlPanel(fig, targets)
    % Tạo panel thông tin và điều khiển
    
    % Panel thông tin mục tiêu
    info_panel = uipanel(fig, ...
        'Title', 'THÔNG TIN MỤC TIÊU CHI TIẾT', ...
        'Position', [0.03, 0.01, 0.60, 0.32], ...
        'BackgroundColor', [0.08, 0.08, 0.12], ...
        'ForegroundColor', [0.95, 0.95, 1], ...
        'FontSize', 11, ...
        'FontWeight', 'bold');
    
    % Tạo bảng cho từng mục tiêu
    target_tables = cell(length(targets), 1);
    for i = 1:length(targets)
        x_pos = 0.01 + (i-1) * 0.135;
        target_tables{i} = uitable(info_panel, ...
            'Position', [x_pos*1600, 10, 220, 230], ...
            'ColumnName', {'Thông số', 'Giá trị'}, ...
            'ColumnWidth', {50, 50}, ...
            'RowName', [], ...
            'FontSize', 9, ...
            'ForegroundColor', [0.9, 0.9, 0.9]);
    end
    
    % Panel điều khiển
    control_panel = uipanel(fig, ...
        'Title', 'ĐIỀU KHIỂN', ...
        'Position', [0.62, 0.01, 0.35, 0.32], ...
        'BackgroundColor', [0.08, 0.08, 0.12], ...
        'ForegroundColor', [0.95, 0.95, 1], ...
        'FontSize', 11, ...
        'FontWeight', 'bold');
    
    % Nút điều khiển
    buttons = struct();
    
    buttons.start = uicontrol(control_panel, ...
        'Style', 'pushbutton', ...
        'String', '▶ BẮT ĐẦU', ...
        'Position', [20, 180, 120, 40], ...
        'FontSize', 11, ...
        'FontWeight', 'bold', ...
        'BackgroundColor', [0.2, 0.6, 0.3], ...
        'ForegroundColor', [1, 1, 1], ...
        'Callback', @(src, evt) startSimulation(src));
    
    buttons.pause = uicontrol(control_panel, ...
        'Style', 'pushbutton', ...
        'String', '⏸ TẠM DỪNG', ...
        'Position', [160, 180, 120, 40], ...
        'FontSize', 11, ...
        'FontWeight', 'bold', ...
        'BackgroundColor', [0.8, 0.6, 0.1], ...
        'ForegroundColor', [1, 1, 1], ...
        'Enable', 'off', ...
        'Callback', @(src, evt) pauseSimulation(src));
    
    buttons.reset = uicontrol(control_panel, ...
        'Style', 'pushbutton', ...
        'String', '🔄 RESET', ...
        'Position', [300, 180, 120, 40], ...
        'FontSize', 11, ...
        'FontWeight', 'bold', ...
        'BackgroundColor', [0.6, 0.2, 0.2], ...
        'ForegroundColor', [1, 1, 1], ...
        'Callback', @(src, evt) resetSimulation(src));
    
    % Nhãn checkbox
    uicontrol(control_panel, ...
        'Style', 'text', ...
        'String', 'CHỈ THỊ TỪ CẤP TRÊN:', ...
        'Position', [20, 140, 400, 25], ...
        'FontSize', 10, ...
        'FontWeight', 'bold', ...
        'BackgroundColor', [0.08, 0.08, 0.12], ...
        'ForegroundColor', [1, 0.8, 0.2], ...
        'HorizontalAlignment', 'left');
    
    % Checkbox cho từng mục tiêu
    checkboxes = cell(length(targets), 1);
    for i = 1:length(targets)
        y_pos = 110 - (i-1) * 30;
        checkboxes{i} = uicontrol(control_panel, ...
            'Style', 'checkbox', ...
            'String', sprintf('%s - %s', targets(i).name, targets(i).type), ...
            'Position', [30, y_pos, 380, 25], ...
            'FontSize', 9, ...
            'BackgroundColor', [0.08, 0.08, 0.12], ...
            'ForegroundColor', [0.9, 0.9, 0.9], ...
            'Callback', @(src, evt) togglePriority(src, i));
    end
end