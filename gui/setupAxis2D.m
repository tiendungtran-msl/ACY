function setupAxis2D(ax)
    % Cấu hình axes 2D
    hold(ax, 'on');
    grid(ax, 'on');
    axis(ax, [-50000, 50000, -20000, 80000]);
    
    xlabel(ax, 'X (km)', 'Color', [0.9, 0.9, 0.9], 'FontSize', 10);
    ylabel(ax, 'Y (km)', 'Color', [0.9, 0.9, 0.9], 'FontSize', 10);
    title(ax, 'TÌNH HÌNH TRÊN KHÔNG - ĐÁNH GIÁ MỨC ĐỘ NGUY HIỂM', ...
          'Color', [0.95, 0.95, 1], 'FontSize', 13, 'FontWeight', 'bold');
    
    % Tùy chỉnh grid
    set(ax, ...
        'Color', [0.05, 0.12, 0.18], ...
        'XColor', [0.7, 0.7, 0.7], ...
        'YColor', [0.7, 0.7, 0.7], ...
        'GridColor', [0.3, 0.3, 0.3], ...
        'GridAlpha', 0.3, ...
        'LineWidth', 0.5, ...
        'FontSize', 9 ...
    );
    
    % Bật minor grid
    ax.XAxis.MinorTick = 'on';
    ax.YAxis.MinorTick = 'on';
    ax.XAxis.MinorTickValues = -60000:5000:60000;
    ax.YAxis.MinorTickValues = -50000:5000:70000;
end