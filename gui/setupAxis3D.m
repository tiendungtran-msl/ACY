function setupAxis3D(ax)
    % Cấu hình axes 3D
    hold(ax, 'on');
    grid(ax, 'on');
    axis(ax, [-50000, 50000, -20000, 80000, 0, 30000]);
    
    xlabel(ax, 'X (km)', 'Color', [0.9, 0.9, 0.9], 'FontSize', 9);
    ylabel(ax, 'Y (km)', 'Color', [0.9, 0.9, 0.9], 'FontSize', 9);
    zlabel(ax, 'H (km)', 'Color', [0.9, 0.9, 0.9], 'FontSize', 9);
    
    % Grid tùy chỉnh cho 3D
    set(ax, ...
        'XTick', -60000:10000:60000, ...
        'YTick', -50000:10000:70000, ...
        'ZTick', 0:5000:30000, ...
        'XTickLabel', -60:10:60, ...
        'YTickLabel', -50:10:70, ...
        'ZTickLabel', 0:5:30);
    title(ax, 'KHÔNG GIAN 3D', ...
          'Color', [0.95, 0.95, 1], 'FontSize', 12, 'FontWeight', 'bold');
    
    set(ax, ...
        'Color', [0.05, 0.12, 0.18], ...
        'XColor', [0.7, 0.7, 0.7], ...
        'YColor', [0.7, 0.7, 0.7], ...
        'ZColor', [0.7, 0.7, 0.7], ...
        'GridColor', [0.3, 0.3, 0.3], ...
        'GridAlpha', 0.3 ...
    );
    
    view(ax, 45, 25);
end